/*
 * What a compiled prototype carries to play routes (code as text, pure): the navigation state with
 * each screen's open parts, and the step that opens and closes them. Emitted once per module that
 * has a route (compile.ts); how the parts move (the overlay layer) is the feel's (feel.ts).
 *
 * - Back closes the topmost overlay first, then goes to the screen before, which opens as it was
 *   left (its bars still showing); leaving a screen closes its overlays.
 */

/** Types and the navigation step: `screens` maps keys to dir (SCREENS has them at runtime). */
