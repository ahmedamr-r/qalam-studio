export const NAV_STEP = [
  "export interface Entry {",
  "  screen: ScreenId;",
  "  /** Its parts that were open, in the order they opened. */",
  "  open: string[];",
  "  /** What the screen remembers on this visit (see INIT). */",
  "  data: Record<string, unknown>;",
  "  /** The item each open part is about (a dish's options: the dish). */",
  "  ctx: Record<string, string>;",
  "  /** How it was gone to, the last time it was (not by going back): a pushed screen pops the way it came. */",
  `  came?: Via["kind"];`,
  "}",
  "",
  "export interface State extends Entry {",
  "  /** Bumps on every move, so each visit is its own element that can enter and leave. */",
  "  visit: number;",
  "  history: Entry[];",
  "  via?: Via;",
  "  /** Shared layers match within a group: smart transitions stay in it, other kinds start a new one. */",
  "  group: number;",
  "  anchors: Record<string, Box>;",
  "  /** What the app remembers across screens. */",
  "  app: AppData;",
  "  /** A scroll a rule asked for (the screen scrolls when `n` changes). */",
  "  scrollTo?: { y: number; n: number };",
  "  /** How close that scroll has come: while it heads there, what the rule picked (a section) stays picked. */",
  "  held?: number;",
  "}",
  "",
  "/** Where the prototype starts: a screen that draws a list starts with the lines its design shows (APP_SEED). */",
  "export const initial = (screen: ScreenId): State => ({ screen, open: [], data: INIT[screen](), ctx: {}, visit: 0, history: [], group: 0, anchors: {}, app: { ...APP_INIT(), ...APP_SEED[screen]?.() } });",
  "",
  "const isBar = (screen: ScreenId, part: string) => PARTS[screen]?.[part]?.kind === \"bar\";",
  "/** The topmost open overlay (bars aren't overlays). */",
  "const topOverlay = (n: State) => [...n.open].reverse().find((p) => !isBar(n.screen, p));",
  "",
  "function move(n: State, to: ScreenId | \"back\", via: Via): State {",
  "  if (to === \"back\") {",
  "    const prev = n.history[n.history.length - 1];",
  "    if (!prev) return n;",
  "    // Back to a screen as it was left: what it remembered, and its bars.",
  "    return { ...n, ...prev, visit: n.visit + 1, history: n.history.slice(0, -1), via: { ...via, back: true, dir: SCREENS[prev.screen].dir }, group: via.kind === \"smart\" ? n.group : n.group + 1, anchors: {}, scrollTo: undefined, held: undefined };",
  "  }",
  "  // The screen left keeps its bars for when you come back; its overlays close.",
  "  const left: Entry = { screen: n.screen, open: n.open.filter((p) => isBar(n.screen, p)), data: n.data, ctx: n.ctx, came: n.came };",
  "  return { ...n, screen: to, open: [], data: INIT[to](), ctx: {}, came: via.kind, visit: n.visit + 1, history: [...n.history, left], via: { ...via, dir: SCREENS[to].dir }, group: via.kind === \"smart\" ? n.group : n.group + 1, anchors: {}, scrollTo: undefined, held: undefined };",
  "}",
  "",
  "/** Open a part, about an item when it has one; what it keeps for itself starts over. */",
  "function openPart(n: State, part: string, anchor?: Box, item?: string): State {",
  "  if (!PARTS[n.screen]?.[part]) return n;",
  "  const fresh = INIT[n.screen]();",
  "  const reset = Object.fromEntries((RESETS[n.screen]?.[part] ?? []).map((v) => [v, fresh[v]]));",
  "  return {",
  "    ...n,",
  "    open: n.open.includes(part) ? n.open : [...n.open, part],",
  "    anchors: anchor ? { ...n.anchors, [part]: anchor } : n.anchors,",
  "    ctx: item !== undefined ? { ...n.ctx, [part]: item } : n.ctx,",
  "    data: { ...n.data, ...reset },",
  "  };",
  "}",
  "",
  "/** The screen scrolled: values that follow scrolling (a compact header, the section in view). */",
  "function scrolled(n: State, y: number, max = Infinity): State {",
  "  const sc = SCROLL[n.screen];",
  "  if (!sc) return n;",
  "  let data = n.data;",
  "  for (const [v, at] of sc.past) if (data[v] !== y > at) data = { ...data, [v]: y > at };",
  "  // A section a tap picked stays picked while the scroll heads there (it may stop short, at the bottom), until you scroll away.",
  "  let held = n.held;",
  "  if (held !== undefined && n.scrollTo) {",
  "    const d = Math.abs(y - Math.min(n.scrollTo.y, max));",
  "    held = d > held + 1 ? undefined : Math.min(held, d);",
  "  }",
  "  if (sc.spy && held === undefined) {",
  "    const { v, marks } = sc.spy;",
  "    // Sections too near the end to reach the top get their turn as the scroll ends: the line that picks one slides down to the last.",
  "    const over = marks.length && max < Infinity ? marks[marks.length - 1][1] - max : 0;",
  "    const ramp = Math.min(over, max);",
  "    const line = y + 1 + (over > 0 && ramp > 0 ? over * Math.min(1, Math.max(0, (y - (max - ramp)) / ramp)) : 0);",
  "    let id = marks[0]?.[0] ?? null;",
  "    for (const [sid, at] of marks) if (line >= at) id = sid;",
  "    if (data[v] !== id) data = { ...data, [v]: id };",
  "  }",
  "  return data === n.data && held === n.held ? n : { ...n, data, held };",
  "}",
  "",
  "/** One step of the prototype: what an action does to where you are (pure; exported for tests and tools). */",
  "export function step(n: State, a: Action, anchor?: Box): State {",
  "  switch (a.do) {",
  "    case \"open\":",
  "      return n.open.includes(a.part) ? n : openPart(n, a.part, anchor);",
  "    case \"close\": {",
  "      const part = a.part ?? topOverlay(n);",
  "      return part && n.open.includes(part) ? { ...n, open: n.open.filter((p) => p !== part) } : n;",
  "    }",
  "    case \"back\": {",
  "      const top = topOverlay(n);",
  "      return top ? { ...n, open: n.open.filter((p) => p !== top) } : move(n, \"back\", BACK);",
  "    }",
  "    case \"go\":",
  "      return move(n, a.to, a.via);",
  "    case \"run\": {",
  "      const rule = RULES[n.screen]?.[a.rule];",
  "      return rule ? rule(n, a.it, anchor) : n;",
  "    }",
  "    case \"scrolled\":",
  "      return scrolled(n, a.y, a.max);",
  "  }",
  "}",
];

/**
 * Bars a screen shows over its pinned bottom (inside it, so they sit above the footer): while `cond`
 * holds, else while open. They slide up from behind what's under them on the platform's motion for
 * bars (MOTION.bar), and back down.
 */
export const barCode = (pad: string, part: string, component: string, cond?: string) => [
  `${pad}<AnimatePresence initial={false}>`,
  `${pad}  {(${cond ?? `open.includes(${JSON.stringify(part)})`}) && (`,
  `${pad}    <motion.div key=${JSON.stringify(part)} initial={{ y: "100%" }} animate={{ y: 0 }} exit={{ y: "100%" }} transition={MOTION.bar}>`,
  `${pad}      <${component} act={act} s={s} />`,
  `${pad}    </motion.div>`,
  `${pad}  )}`,
  `${pad}</AnimatePresence>`,
];
